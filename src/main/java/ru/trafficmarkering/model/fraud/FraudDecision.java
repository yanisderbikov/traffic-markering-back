package ru.trafficmarkering.model.fraud;

/** Решение админа по подозрительному отклику. */
public enum FraudDecision {
    /** Просмотры честные: зачисление размораживается, автоматика статус больше не трогает */
    VERIFIED,
    /** Накрутка подтверждена: начисление обнуляется, криатор получает страйк */
    FRAUD,
    /** Снять ручную отметку и вернуть отклик автоматическому скорингу */
    AUTO
}
